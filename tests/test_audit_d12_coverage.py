"""Regression floor for D12 (`sd_coverage_changed`) — merge-base measurement.

D12 used to diff ``harness/`` from a stored baseline commit. A squash merge
could orphan that commit or move the baseline between a PR's measurement and
merge, so a covered PR lost its verdict without changing a line. The fix is
mechanical:

1. the diff base is the runtime merge-base (``HARNESS_D12_BASE`` in CI, the
   checkout's ``origin/main`` locally), never a stored branch SHA;
2. executed lines come from current-tree coverage, regenerated by the traced
   battery when the committed fast-path document does not name that base;
3. a missing base or missing coverage fails closed in CI and is a visible
   SKIP locally;
4. S5's ruff resolution is the shared resolver, and a missing tool is a named
   failure rather than an opaque ``No module named ruff``.
5. a fail-open SKIP is ``skip`` in the text table and JSON receipt, and it
   contributes to neither the measured-check numerator nor denominator.

These tests pin the parser, the merge-base decision, the actual ratio over a
real temporary git diff, the skip accounting through ``main``, and the
explicit S5 disposition.
"""

import contextlib
import importlib.util
import io
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest import mock

_ROOT = Path(__file__).resolve().parents[1]
_AUDIT_PATH = _ROOT / "audits" / "self" / "audit.py"
_RUNBOOK_PATH = _ROOT / "docs" / "audit-triage.md"


def _load_audit():
    spec = importlib.util.spec_from_file_location("_d12_audit", _AUDIT_PATH)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _git(root, *args):
    return subprocess.run(["git", *args], cwd=str(root), capture_output=True,
                          text=True, encoding="utf-8", errors="replace")


class _TempRepo:
    """A real git repo with a base commit and one modifiable harness file."""

    def __init__(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        (self.root / "harness").mkdir()
        (self.root / "harness" / "mod.py").write_text(
            "def value():\n    return 1\n", encoding="utf-8")
        _git(self.root, "init", "-q")
        _git(self.root, "config", "user.email", "d12@example.invalid")
        _git(self.root, "config", "user.name", "D12 Test")
        _git(self.root, "add", "harness/mod.py")
        _git(self.root, "commit", "-q", "-m", "base")
        self.base = _git(self.root, "rev-parse", "HEAD").stdout.strip()

    def set_source(self, text):
        (self.root / "harness" / "mod.py").write_text(text, encoding="utf-8")

    def close(self):
        self.tmp.cleanup()


class D12MergeBaseTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.audit = _load_audit()

    def test_parser_reads_added_lines_per_file(self):
        diff = (
            "diff --git a/harness/a.py b/harness/a.py\n"
            "--- a/harness/a.py\n"
            "+++ b/harness/a.py\n"
            "@@ -1,2 +1,3 @@\n"
            "+new\n"
            " same\n"
            "+another\n"
        )
        self.assertEqual(self.audit._parse_added_lines(diff),
                         {"harness/a.py": {1, 3}})

    def test_statement_lines_ignore_docstrings(self):
        source = (
            '"""module docstring"""\n'
            "def f():\n"
            '    """function docstring"""\n'
            "    return 1\n"
        )
        # The def line is not counted when its body opens with a docstring;
        # the return is the first statement that can emit a trace event.
        self.assertEqual(self.audit._statement_lines(source), {4})

    def test_ratio_counts_only_executable_added_lines(self):
        root = Path(tempfile.mkdtemp(prefix="d12-ratio-"))
        try:
            (root / "harness").mkdir()
            (root / "harness" / "m.py").write_text(
                "def f():\n    x = 1\n    return x\n", encoding="utf-8")
            checked, executed, gaps = self.audit._coverage_ratio(
                root, {"harness/m.py": {2, 3}}, {"harness/m.py": [2]})
            self.assertEqual((checked, executed), (2, 1))
            self.assertEqual(gaps, {"harness/m.py": [3]})
        finally:
            import shutil
            shutil.rmtree(root, ignore_errors=True)

    def test_base_is_the_merge_base_of_the_event_ref(self):
        repo = _TempRepo()
        try:
            # One descendant commit so the merge-base is the base, not HEAD.
            (repo.root / "tests").mkdir()
            (repo.root / "tests" / "test_x.py").write_text("", encoding="utf-8")
            _git(repo.root, "add", "tests/test_x.py")
            _git(repo.root, "commit", "-q", "-m", "child")
            with mock.patch.object(self.audit, "ROOT", repo.root), \
                 mock.patch.dict(os.environ, {"HARNESS_D12_BASE": repo.base}):
                base, source = self.audit.d12_base_ref()
            self.assertEqual(base, repo.base)
            self.assertEqual(source, "HARNESS_D12_BASE")
        finally:
            repo.close()

    def test_unresolvable_base_is_a_named_failure_in_ci(self):
        score, evidence = self.audit.d12_no_base("no origin/main", in_ci=True)
        self.assertEqual(score, 0.0)
        self.assertTrue(evidence.startswith("FAIL"))
        self.assertIn("changed-line coverage was not measured", evidence)
        self.assertEqual(self.audit._mark(score, evidence), "FAIL")

    def test_unresolvable_base_is_a_visible_skip_locally(self):
        score, evidence = self.audit.d12_no_base("no origin/main", in_ci=False)
        self.assertEqual(score, 1.0)
        self.assertTrue(evidence.startswith("SKIP (fail-open)"))
        self.assertEqual(self.audit._mark(score, evidence), "skip")

    def test_skip_is_excluded_from_the_dimension_mean(self):
        rows = [
            {"id": "measured-pass", "score": 1.0, "status": "pass",
             "evidence": "measured"},
            {"id": "measured-fail", "score": 0.0, "status": "FAIL",
             "evidence": "measured"},
            {"id": "D12", "score": None, "status": "skip",
             "evidence": "SKIP (fail-open): no merge-base"},
        ]
        mean, measured, skipped = self.audit._dimension_result(rows)
        self.assertAlmostEqual(mean, 0.5)
        self.assertEqual([r["id"] for r in measured],
                         ["measured-pass", "measured-fail"])
        self.assertEqual([r["id"] for r in skipped], ["D12"])

    def test_all_skip_dimension_has_no_measurement_to_average(self):
        rows = [{"id": "D12", "score": None, "status": "skip",
                 "evidence": "SKIP (fail-open): no merge-base"}]
        mean, measured, skipped = self.audit._dimension_result(rows)
        self.assertIsNone(mean)
        self.assertEqual(measured, [])
        self.assertEqual([r["id"] for r in skipped], ["D12"])

    def test_unreachable_merge_base_fails_closed_in_ci(self):
        score, evidence = self.audit.d12_unreachable("f" * 40, in_ci=True)
        self.assertEqual(score, 0.0)
        self.assertTrue(evidence.startswith("FAIL"))
        self.assertIn("merge-base", evidence)

    def test_each_skip_path_emits_an_audible_warning(self):
        import contextlib
        import io

        for fn, in_ci, marker in (
                (self.audit.d12_unreachable, False, "[warn]"),
                (self.audit.d12_unreachable, True, "[FATAL]"),
                (self.audit.d12_no_base, False, "[warn]"),
                (self.audit.d12_no_base, True, "[FATAL]"),
                (self.audit.d12_coverage_unavailable, False, "[warn]"),
                (self.audit.d12_coverage_unavailable, True, "[FATAL]")):
            buf = io.StringIO()
            with contextlib.redirect_stderr(buf):
                fn("x" * 40, in_ci=in_ci)
            self.assertIn(marker, buf.getvalue(),
                          f"no {marker} warning emitted (in_ci={in_ci})")

    def test_coverage_document_must_name_the_resolved_merge_base(self):
        with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
            json.dump({"commit": "f" * 40, "modules": {}}, f)
            path = f.name
        try:
            with mock.patch.dict(os.environ, {"HARNESS_D12_BASELINE": path}):
                doc, source = self.audit.d12_coverage_doc("a" * 40)
            self.assertIsNone(doc)
            self.assertIn("not the resolved merge-base", source)
        finally:
            os.unlink(path)

    def test_stale_fast_path_regenerates_current_tree_coverage(self):
        tmp = tempfile.TemporaryDirectory()
        try:
            root = Path(tmp.name)
            (root / "audits" / "self").mkdir(parents=True)
            base = "a" * 40
            captured = {}

            def fake_run(argv, **kwargs):
                if "refresh_coverage_baseline.py" in argv[1]:
                    captured["argv"] = argv
                    out = Path(argv[argv.index("--out") + 1])
                    out.write_text(json.dumps({
                        "commit": base,
                        "modules": {"harness/mod.py": [1, 2]},
                    }), encoding="utf-8")
                    return SimpleNamespace(returncode=0, stdout="coverage written",
                                           stderr="")
                # Any git call in this test is unexpected; make it obvious.
                raise AssertionError(argv)

            with mock.patch.object(self.audit, "ROOT", root), \
                 mock.patch.object(self.audit, "HERE", root / "audits" / "self"), \
                 mock.patch.object(self.audit, "hermetic_suite_env",
                                   return_value=({}, [])), \
                 mock.patch.object(self.audit.subprocess, "run", side_effect=fake_run), \
                 mock.patch.dict(os.environ, {}, clear=False):
                os.environ.pop("HARNESS_D12_BASELINE", None)
                doc, source = self.audit.d12_coverage_doc(base)
            self.assertIsNotNone(doc)
            self.assertIn("traced battery at merge-base", source)
            self.assertIn("--out", captured["argv"])
            self.assertEqual(doc["commit"], base)
        finally:
            tmp.cleanup()

    def test_real_diff_passes_then_fails_on_the_same_measurement(self):
        repo = _TempRepo()
        try:
            repo.set_source("def value():\n    return 2\n")
            base = repo.base
            with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
                json.dump({"commit": base,
                           "modules": {"harness/mod.py": [1, 2]}}, f)
                coverage = f.name
            try:
                env = {"HARNESS_D12_BASE": base, "HARNESS_D12_BASELINE": coverage}
                with mock.patch.object(self.audit, "ROOT", repo.root), \
                     mock.patch.dict(os.environ, env), \
                     mock.patch.object(self.audit, "_IN_CI", True):
                    score, evidence = self.audit.sd_coverage_changed()
                self.assertEqual(score, 1.0, evidence)
                self.assertIn("1/1 = 100%", evidence)
                self.assertIn("merge-base", evidence)

                with open(coverage, "w", encoding="utf-8") as f:
                    json.dump({"commit": base,
                               "modules": {"harness/mod.py": [1]}}, f)
                with mock.patch.object(self.audit, "ROOT", repo.root), \
                     mock.patch.dict(os.environ, env), \
                     mock.patch.object(self.audit, "_IN_CI", True):
                    score, evidence = self.audit.sd_coverage_changed()
                self.assertEqual(score, 0.0, evidence)
                self.assertIn("0/1 = 0%", evidence)
                self.assertIn("untested", evidence)
            finally:
                os.unlink(coverage)
        finally:
            repo.close()

    def test_no_executable_change_is_reported_not_silently_scored(self):
        repo = _TempRepo()
        try:
            with mock.patch.object(self.audit, "ROOT", repo.root), \
                 mock.patch.dict(os.environ, {"HARNESS_D12_BASE": repo.base}), \
                 mock.patch.object(self.audit, "_IN_CI", True), \
                 mock.patch.object(self.audit, "d12_coverage_doc",
                                   side_effect=AssertionError("must not trace")):
                score, evidence = self.audit.sd_coverage_changed()
            self.assertEqual(score, 1.0)
            self.assertIn("no executable harness changes", evidence)
        finally:
            repo.close()


class AuditSkipSurfaceTests(unittest.TestCase):
    """The real audit entry point reports a SKIP without passing credit."""

    @classmethod
    def setUpClass(cls):
        cls.audit = _load_audit()

    def test_skip_is_explicit_in_text_and_receipt_and_not_scored(self):
        def fake_evaluate(evidence):
            sd = evidence.get("SD", {})
            score = sd.get("score")
            return {
                "dimensions": {
                    "SD": {"name": self.audit.DIM_NAMES["SD"],
                           "score": score,
                           "evaluated": score is not None},
                },
                "scores": {"SD": score},
                "bar_95_pass": score is not None and score >= 9.5,
                "is_fallback": True,
                "model": "fake",
            }

        fake_policy = mock.Mock()
        fake_policy.evaluate_audit_dimensions.side_effect = fake_evaluate

        def measured_pass():
            return 1.0, "measured pass"

        def measured_fail():
            return 0.0, "measured fail"

        tmp = tempfile.TemporaryDirectory()
        try:
            root = Path(tmp.name) / "repo"
            here = root / "audits" / "self"
            here.mkdir(parents=True)
            stdout, stderr = io.StringIO(), io.StringIO()
            with mock.patch.object(self.audit, "ROOT", root), \
                 mock.patch.object(self.audit, "HERE", here), \
                 mock.patch.object(self.audit, "_IN_CI", False), \
                 mock.patch.object(self.audit, "CHECKS", {"SD": [
                     ("D-pass", "measured pass", measured_pass),
                     ("D-fail", "measured fail", measured_fail),
                     ("D12", "changed lines suite-executed (coverage)",
                      self.audit.sd_coverage_changed),
                 ]}), \
                 mock.patch.object(self.audit, "d12_base_ref",
                                   return_value=("", "test: no merge-base")), \
                 mock.patch.object(self.audit, "_compose_audit_jev_policy",
                                   return_value=fake_policy), \
                 mock.patch("harness.config.load_settings",
                            return_value=SimpleNamespace(max_cost=0.0,
                                                         jev_api_key=None)), \
                 mock.patch.object(sys, "argv", ["audit.py"]), \
                 contextlib.redirect_stdout(stdout), \
                 contextlib.redirect_stderr(stderr):
                rc = self.audit.main()

            text = stdout.getvalue()
            self.assertEqual(rc, 1, text)
            self.assertIn("D12 skip", text)
            self.assertIn("5.00/10 (1/2 checks fully satisfied; 1 skipped)", text)
            self.assertIn("SKIP (fail-open)", text)

            payload = json.loads((here / "round2_scores.json").read_text(
                encoding="utf-8"))
            rows = {r["id"]: r for r in payload["checks"]["SD"]}
            self.assertEqual(rows["D12"]["status"], "skip")
            self.assertIsNone(rows["D12"]["score"])
            self.assertTrue(rows["D12"]["evidence"].startswith("SKIP (fail-open)"))
            self.assertEqual(payload["skipped_checks"]["SD"], ["D12"])
            # A skip's nominal fail-open 1.0 must not lift the 5.00 measured
            # score to 6.67 as a third check would.
            self.assertEqual(payload["scores"]["SD"], 5.0)

            evidence = fake_policy.evaluate_audit_dimensions.call_args.args[0]
            sd = evidence["SD"]
            self.assertEqual(sd["score"], 5.0)
            self.assertEqual(sd["checks_count"], 2)
            self.assertEqual(sd["checks_satisfied"], 1)
            self.assertEqual(sd["checks_skipped"], 1)
            self.assertEqual([c["id"] for c in sd["checks"]],
                             ["D-pass", "D-fail"])
        finally:
            tmp.cleanup()


class S5DispositionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.audit = _load_audit()

    def test_s5_runs_through_the_shared_ruff_resolver(self):
        seen = {}

        def fake_run(argv, **kwargs):
            seen["argv"] = argv
            return SimpleNamespace(returncode=0, stdout="", stderr="")

        with mock.patch("harness.tools.ruff_argv",
                        return_value=(sys.executable, "-m", "ruff")), \
             mock.patch.object(self.audit.subprocess, "run", side_effect=fake_run):
            score, evidence = self.audit.sm_lint()
        self.assertEqual(score, 1.0)
        self.assertEqual(seen["argv"][:3], [sys.executable, "-m", "ruff"])
        self.assertIn("shared resolver", evidence)

    def test_s5_missing_ruff_is_a_named_environment_failure(self):
        from harness.errors import HarnessError
        with mock.patch("harness.tools.ruff_argv",
                        side_effect=HarnessError("no ruff: install .[dev]")):
            score, evidence = self.audit.sm_lint()
        self.assertEqual(score, 0.0)
        self.assertIn("S5 ruff unresolved", evidence)
        self.assertIn("no ruff", evidence)

    def test_runbook_records_the_s5_and_local_suite_disposition(self):
        text = _RUNBOOK_PATH.read_text(encoding="utf-8")
        self.assertIn("No module named ruff", text)
        self.assertIn("test_hourglass_end_to_end", text)
        self.assertIn("test_dogfood", text)
        self.assertIn("merge-base", text)
        self.assertIn("CI is authoritative", text)


if __name__ == "__main__":
    unittest.main()
